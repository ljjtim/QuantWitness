def test_mainline_layers_only_import_same_or_lower_layers() -> None:
    for layer, allowed in LAYER_ALLOWED_PREFIXES.items():
        directory = PACKAGE_DIR / layer
        assert directory.is_dir()
        for path in directory.rglob("*.py"):
            tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
            for module in iter_imported_modules(path, tree):
                assert module != INVALID_RELATIVE_IMPORT, (
                    f"{path} 使用了越过 research_pipeline 包根的相对导入"
                )
                if module == "research_pipeline" or module.startswith(
                    "research_pipeline."
                ):
                    assert matches_module_prefix(module, allowed), (
                        f"{layer} 层发生反向依赖: {path} -> {module}"
                    )


def test_package_modules_have_no_ast_import_cycle() -> None:
    package_root = PACKAGE_DIR / "packages"
    module_paths = {}
    for path in package_root.glob("*.py"):
        name = (
            "research_pipeline.packages"
            if path.name == "__init__.py"
            else f"research_pipeline.packages.{path.stem}"
        )
        module_paths[name] = path
    edges = {name: set() for name in module_paths}
    for name, path in module_paths.items():
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
        edges[name].update(
            imported
            for imported in iter_imported_modules(path, tree)
            if imported in module_paths and imported != name
        )

    compiler = "research_pipeline.packages.compiler"
    operator_graph = "research_pipeline.packages.operator_graph"
    assert operator_graph not in edges[compiler]
    assert compiler not in edges[operator_graph]

    visiting: set[str] = set()
    visited: set[str] = set()

    def visit(module: str) -> None:
        assert module not in visiting, f"packages 包内出现 AST import 循环: {module}"
        if module in visited:
            return
        visiting.add(module)
        for dependency in edges[module]:
            visit(dependency)
        visiting.remove(module)
        visited.add(module)

    for module in edges:
        visit(module)


