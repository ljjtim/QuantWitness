def test_relative_import_resolver_handles_nested_and_invalid_levels() -> None:
    nested = ast.parse("from .time import TimeContractError\n")
    invalid = ast.parse("from ...v2 import contracts\n")

    assert "research_pipeline.domain.time" in iter_imported_modules(
        PACKAGE_DIR / "domain" / "models.py",
        nested,
    )
    assert INVALID_RELATIVE_IMPORT in iter_imported_modules(
        PACKAGE_DIR / "domain" / "models.py",
        invalid,
    )


def test_mainline_package_roots_have_explicit_version_free_public_api() -> None:
    for layer, expected in EXPECTED_PUBLIC_API.items():
        module = importlib.import_module(f"research_pipeline.{layer}")
        assert set(module.__all__) == expected
        assert all(hasattr(module, name) for name in expected)
        assert all("V2" not in name for name in expected)


